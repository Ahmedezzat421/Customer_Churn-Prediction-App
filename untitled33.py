def predict_churn(customer_data, model, scaler, training_columns, num_cols):
    """
    Predicts churn and churn probability for a new customer.

    Parameters:
    - customer_data: dict or pd.DataFrame with keys: 'Tenure', 'MonthlyCharges', 'TotalCharges', 'Contract', 'TechSupport'
    - model: trained PyTorch ChurnMLP model
    - scaler: fitted StandardScaler instance used for training
    - training_columns: list of columns in the training set after encoding (e.g., X_train_scaled.columns)
    - num_cols: list of numerical columns to scale
    """
    # 1. Convert input dictionary to DataFrame if needed
    if isinstance(customer_data, dict):
        df_input = pd.DataFrame([customer_data])
    else:
        df_input = customer_data.copy()

    # 2. Apply one-hot encoding matching the training stage
    df_encoded = pd.get_dummies(df_input, columns=['Contract', 'TechSupport'])

    # Reindex to ensure same features/columns as training features (fill missing with False/0)
    for col in training_columns:
        if col not in df_encoded.columns:
            df_encoded[col] = 0

    # Ensure correct column ordering
    df_encoded = df_encoded[training_columns]

    # 3. Scale numerical columns
    df_scaled = df_encoded.copy()
    df_scaled[num_cols] = scaler.transform(df_encoded[num_cols].astype(float))

    # Convert scaled features to numpy array
    features_np = df_scaled.values.astype('float32')

    # 4. Convert to PyTorch float tensor
    features_tensor = torch.tensor(features_np)

    # 5. Run prediction using PyTorch MLP model
    model.eval()
    with torch.no_grad():
        output = model(features_tensor)
        prob = output.item()

    # 6. Determine binary class prediction based on threshold
    prediction = "Churn" if prob >= 0.5 else "No Churn"

    # 7. Return classification label and probability percentage
    return prediction, prob * 100

